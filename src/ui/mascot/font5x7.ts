/** Glyph for a character: lowercase maps to uppercase, unknown characters render as space. */
export function glyphFor(ch: string): readonly string[] {
  return FONT_5X7[ch.toUpperCase()] ?? FONT_5X7[ch] ?? FONT_5X7[" "] ?? [];
}

/** Lit cells for a string, in dot units (each glyph is 5 wide plus 1 gap). */
export function layoutLedText(text: string): { cells: { x: number; y: number }[]; width: number; height: number } {
  const chars = Array.from(text);
  const cells: { x: number; y: number }[] = [];
  chars.forEach((ch, i) => {
    glyphFor(ch).forEach((row, y) => {
      for (let x = 0; x < GLYPH_W; x++) if (row[x] === "#") cells.push({ x: i * (GLYPH_W + 1) + x, y });
    });
  });
  return { cells, width: Math.max(0, chars.length * (GLYPH_W + 1) - 1), height: GLYPH_H };
}
